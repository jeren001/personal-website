const getSavedLanguage = () => {
  try {
    return localStorage.getItem('jeren-language') === 'zh' ? 'zh' : 'en';
  } catch {
    return 'en';
  }
};

const languageState = {
  current: getSavedLanguage(),
  originals: new WeakMap(),
  attributeOriginals: new WeakMap(),
};

const translated = (text) => languageState.current === 'zh' ? (translations[text] || text) : text;

const translatePage = () => {
  document.documentElement.lang = languageState.current === 'zh' ? 'zh-CN' : 'en';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement || ['SCRIPT', 'STYLE'].includes(node.parentElement.tagName)) continue;
    if (!languageState.originals.has(node)) languageState.originals.set(node, node.nodeValue);
    const original = languageState.originals.get(node);
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    const core = original.trim();
    node.nodeValue = core ? `${leading}${translated(core)}${trailing}` : original;
  }

  document.querySelectorAll('[alt], [aria-label], [title], meta[name="description"], meta[property="og:title"], meta[property="og:description"]').forEach((element) => {
    let originalAttributes = languageState.attributeOriginals.get(element);
    if (!originalAttributes) {
      originalAttributes = {};
      languageState.attributeOriginals.set(element, originalAttributes);
    }
    ['alt', 'aria-label', 'title', 'content'].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (!Object.prototype.hasOwnProperty.call(originalAttributes, attribute)) {
        originalAttributes[attribute] = element.getAttribute(attribute);
      }
      const original = originalAttributes[attribute];
      element.setAttribute(attribute, translated(original));
    });
  });

  const pageTitles = { 'home-page': 'Jeren | 软件工程学生 | 个人网站', 'about-page': 'Jeren | 关于 | 软件工程学生', 'projects-page': 'Jeren | 项目 | 软件工程学生', 'contact-page': 'Jeren | 联系 | 软件工程学生' };
  if (languageState.current === 'zh') {
    const pageClass = Object.keys(pageTitles).find((className) => document.body.classList.contains(className));
    if (pageClass) document.title = pageTitles[pageClass];
  } else if (document.title.includes('|')) {
    document.title = document.title.replace(/软件工程学生|个人网站|关于|项目|联系/g, (word) => ({ 软件工程学生: 'Software Engineering Student', 个人网站: 'Personal Website', 关于: 'About', 项目: 'Projects', 联系: 'Contact' }[word]));
  }

  document.querySelectorAll('[data-language]').forEach((button) => {
    const active = button.dataset.language === languageState.current;
    button.setAttribute('aria-pressed', String(active));
  });
};

document.addEventListener('DOMContentLoaded', () => {
  const body = document.body;
  const menuButton = document.querySelector('.menu-toggle');
  const navigation = document.querySelector('.site-nav');
  const themeToggle = document.getElementById('theme-toggle');

  // Keep the selected color theme across page visits.
  const savedTheme = localStorage.getItem('jeren-theme');
  const preferredTheme = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';

  const applyTheme = (theme) => {
    const isDark = theme === 'dark';
    body.classList.toggle('is-dark', isDark);

    if (themeToggle) {
      themeToggle.textContent = translated(isDark ? 'Light' : 'Dark');
      themeToggle.setAttribute('aria-pressed', String(isDark));
      themeToggle.setAttribute('aria-label', translated(`Switch to ${isDark ? 'light' : 'dark'} mode`));
    }
  };

  const setLanguage = (language) => {
    languageState.current = language === 'zh' ? 'zh' : 'en';
    try {
      localStorage.setItem('jeren-language', languageState.current);
    } catch {
      // The page still switches language when storage is unavailable.
    }

    translatePage();
    applyTheme(body.classList.contains('is-dark') ? 'dark' : 'light');

    if (menuButton) {
      const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
      menuButton.textContent = translated(isOpen ? 'Close' : 'Menu');
    }
  };

  applyTheme(savedTheme || preferredTheme);

  translatePage();
  document.addEventListener('click', (event) => {
    const languageButton = event.target instanceof Element
      ? event.target.closest('[data-language]')
      : null;
    if (!languageButton) return;
    event.preventDefault();
    setLanguage(languageButton.dataset.language);
  });

  if (themeToggle) {
    themeToggle.addEventListener('click', () => {
      const nextTheme = body.classList.contains('is-dark') ? 'light' : 'dark';
      localStorage.setItem('jeren-theme', nextTheme);
      applyTheme(nextTheme);
    });
  }

  // Toggle the mobile navigation and close it after a link is selected.
  if (menuButton && navigation) {
    const closeNavigation = () => {
      navigation.classList.remove('is-open');
      menuButton.setAttribute('aria-expanded', 'false');
      menuButton.textContent = translated('Menu');
    };

    menuButton.addEventListener('click', () => {
      const isOpen = navigation.classList.toggle('is-open');
      menuButton.setAttribute('aria-expanded', String(isOpen));
      menuButton.textContent = translated(isOpen ? 'Close' : 'Menu');
    });

    navigation.querySelectorAll('a').forEach((link) => {
      link.addEventListener('click', closeNavigation);
    });

    document.addEventListener('click', (event) => {
      if (!navigation.contains(event.target) && !menuButton.contains(event.target)) {
        closeNavigation();
      }
    });
  }

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
      navigation?.classList.remove('is-open');
      menuButton?.setAttribute('aria-expanded', 'false');
      if (menuButton) menuButton.textContent = translated('Menu');
    }
  });

  // Smoothly scroll to any future in-page links.
  document.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener('click', (event) => {
      const target = document.querySelector(link.getAttribute('href'));
      if (!target) return;

      event.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  });

  // Mark the current page in the navigation even if a page is opened directly.
  const currentPage = window.location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.site-nav a').forEach((link) => {
    const linkPage = link.getAttribute('href');
    const isCurrent = linkPage === currentPage || (currentPage === '' && linkPage === 'index.html');
    link.classList.toggle('is-current', isCurrent);
    if (isCurrent) link.setAttribute('aria-current', 'page');
    else link.removeAttribute('aria-current');
  });

  // Reveal page sections as they enter the viewport.
  const revealTargets = document.querySelectorAll('main section:not(.hero):not(.page-hero)');
  if ('IntersectionObserver' in window) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      });
    }, { threshold: 0.12 });

    revealTargets.forEach((section) => {
      section.classList.add('reveal');
      revealObserver.observe(section);
    });
  } else {
    revealTargets.forEach((section) => section.classList.add('is-visible'));
  }

  // Show a friendly placeholder instead of a broken gallery image.
  document.querySelectorAll('[data-gallery-image]').forEach((image) => {
    const showPlaceholder = () => {
      const card = image.closest('.life-card');
      if (card) card.classList.add('is-missing');
    };

    image.addEventListener('error', showPlaceholder);
    if (image.complete && image.naturalWidth === 0) showPlaceholder();
  });

  // Keep the profile card polished when its replaceable image is unavailable.
  document.querySelectorAll('[data-profile-image]').forEach((image) => {
    const showProfilePlaceholder = () => {
      const frame = image.closest('.profile-image-fallback');
      if (frame) frame.classList.add('is-missing');
    };

    image.addEventListener('error', showProfilePlaceholder);
    if (image.complete && image.naturalWidth === 0) showProfilePlaceholder();
  });

  // Build the project details dialog from the existing project card content.
  const projectCards = Array.from(document.querySelectorAll('.project-card'))
    .filter((card) => !card.querySelector('.project-link'));
  let activeProjectCard = null;

  const createProjectModal = () => {
    const modal = document.createElement('div');
    modal.id = 'project-modal';
    modal.className = 'project-modal';
    modal.setAttribute('aria-hidden', 'true');
    modal.innerHTML = `
      <div class="project-modal-panel" role="dialog" aria-modal="true" aria-labelledby="project-modal-title">
        <button class="project-modal-close" type="button" aria-label="${translated('Close project details')}">×</button>
        <p class="eyebrow">${translated('Project details')}</p>
        <h2 class="project-modal-title" id="project-modal-title"></h2>
        <p class="project-modal-copy"></p>
      </div>
    `;
    document.body.appendChild(modal);
    return modal;
  };

  if (projectCards.length) {
    const projectModal = createProjectModal();
    const modalTitle = projectModal.querySelector('.project-modal-title');
    const modalCopy = projectModal.querySelector('.project-modal-copy');
    const closeButton = projectModal.querySelector('.project-modal-close');

    const closeProjectModal = () => {
      projectModal.classList.remove('is-open');
      projectModal.setAttribute('aria-hidden', 'true');
      activeProjectCard?.focus();
      activeProjectCard = null;
    };

    const openProjectModal = (card) => {
      activeProjectCard = card;
      modalTitle.textContent = card.querySelector('h3')?.textContent || translated('Project details');
      modalCopy.textContent = card.querySelector('p')?.textContent || translated('More project details will be added soon.');
      projectModal.classList.add('is-open');
      projectModal.setAttribute('aria-hidden', 'false');
      closeButton.focus();
    };

    projectCards.forEach((card) => {
      card.setAttribute('role', 'button');
      card.setAttribute('tabindex', '0');
      card.setAttribute('aria-label', `${translated('Open details for')} ${card.querySelector('h3')?.textContent || translated('project')}`);
      card.addEventListener('click', (event) => {
        if (event.target.closest('a, button')) return;
        openProjectModal(card);
      });
      card.addEventListener('keydown', (event) => {
        if (event.key === 'Enter' || event.key === ' ') {
          event.preventDefault();
          openProjectModal(card);
        }
      });
    });

    closeButton.addEventListener('click', closeProjectModal);
    projectModal.addEventListener('click', (event) => {
      if (event.target === projectModal) closeProjectModal();
    });
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape' && projectModal.classList.contains('is-open')) closeProjectModal();
    });
  }

  // Validate the contact form before showing its success message.
  const contactForm = document.querySelector('[data-contact-form]');
  const formStatus = document.querySelector('[data-form-status]');

  if (contactForm && formStatus) {
    const nameInput = contactForm.querySelector('#name');
    const emailInput = contactForm.querySelector('#email');
    const messageInput = contactForm.querySelector('#message');

    contactForm.addEventListener('submit', (event) => {
      event.preventDefault();
      const emailIsValid = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(emailInput.value.trim());
      const fieldsAreValid = nameInput.value.trim() && emailIsValid && messageInput.value.trim();

      [nameInput, emailInput, messageInput].forEach((field) => {
        field.removeAttribute('aria-invalid');
      });
      formStatus.classList.remove('form-error', 'form-success');

      if (!fieldsAreValid) {
        if (!nameInput.value.trim()) nameInput.setAttribute('aria-invalid', 'true');
        if (!emailIsValid) emailInput.setAttribute('aria-invalid', 'true');
        if (!messageInput.value.trim()) messageInput.setAttribute('aria-invalid', 'true');
        formStatus.textContent = translated('Please check your name, email, and message before sending.');
        formStatus.classList.add('form-error');
        return;
      }

      formStatus.textContent = translated('Thank you. Your message has been received.');
      formStatus.classList.add('form-success');
      contactForm.reset();
    });
  }

  document.querySelectorAll('[data-year]').forEach((element) => {
    element.textContent = new Date().getFullYear();
  });

  // Add a small pointer-following ring and hover state on pointer devices.
  if (window.matchMedia('(pointer: fine)').matches) {
    const cursor = document.createElement('div');
    cursor.className = 'cursor-follow';
    cursor.setAttribute('aria-hidden', 'true');
    document.body.appendChild(cursor);

    window.addEventListener('pointermove', (event) => {
      cursor.style.left = `${event.clientX}px`;
      cursor.style.top = `${event.clientY}px`;
    });

    document.querySelectorAll('a, button, .project-card, .life-image-wrap').forEach((element) => {
      element.addEventListener('mouseenter', () => cursor.classList.add('is-hovering'));
      element.addEventListener('mouseleave', () => cursor.classList.remove('is-hovering'));
    });
  }
});
